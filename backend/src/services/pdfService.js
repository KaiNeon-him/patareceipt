const PDFDocument = require('pdfkit');
const { pipeline } = require('stream');
const { promisify } = require('util');
const appConfig = require('../config/app');

const streamToBuffer = promisify(pipeline);

const maskPhone = (phone) => {
  if (!phone) return '';
  const digits = phone.replace(/\D/g, '');
  // Normalize to +254XXXXXXXXX format
  if (digits.startsWith('254')) return '+' + digits;
  if (digits.startsWith('0') && digits.length === 10) return '+254' + digits.slice(1);
  return '+' + digits;
};

const formatCurrency = (amount, currency = 'KES') => {
  const symbol = currency === 'KES' ? 'KSh' : '$';
  return symbol + ' ' + amount.toFixed(2);
};

const generateReceiptPdf = async ({ receipt_id, client_name, client_phone, total_amount, terms_and_notes, items, created_at, business_name, default_currency = 'KES' }) => {
  return new Promise((resolve, reject) => {
    const chunks = [];
    const doc = new PDFDocument({ size: 'A4', margin: 50 });

    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    // Header
    doc.fontSize(20).font('Helvetica-Bold').fillColor('#1a1a2e').text('PataReceipt', 50, 40);
    doc.fontSize(10).font('Helvetica').fillColor('#4a4a4a').text('Secured by PataReceipt', 50, 65, { align: 'right' });
    doc.fontSize(12).font('Helvetica-Bold').text('RECEIPT', 400, 45, { align: 'right' });
    doc.fontSize(10).font('Helvetica').text(receipt_id, 400, 60, { align: 'right' });

    // Divider
    doc.moveTo(50, 85).lineTo(550, 85).strokeColor('#1a1a2e').lineWidth(2).stroke();

    // Business info
    doc.fontSize(10).font('Helvetica-Bold').text('From:', 50, 100);
    doc.fontSize(10).font('Helvetica').text(business_name || 'PataReceipt User', 50, 112);

    // Client info
    doc.fontSize(10).font('Helvetica-Bold').text('To:', 300, 100);
    doc.fontSize(10).font('Helvetica').text(client_name, 300, 112);
    doc.fontSize(10).font('Helvetica').text('Phone: ' + maskPhone(client_phone), 300, 124);

    // Receipt details
    doc.fontSize(10).font('Helvetica-Bold').text('Receipt ID:', 50, 145);
    doc.fontSize(10).font('Helvetica').text(receipt_id, 120, 145);
    doc.fontSize(10).font('Helvetica-Bold').text('Date:', 50, 158);
    doc.fontSize(10).font('Helvetica').text(new Date(created_at).toLocaleDateString('en-KE'), 120, 158);

    // Items table
    let y = 185;
    doc.fontSize(10).font('Helvetica-Bold').fillColor('#1a1a2e');
    doc.text('Item', 50, y);
    doc.text('Qty', 300, y);
    doc.text('Price', 400, y);
    doc.text('Total', 500, y);
    doc.moveTo(50, y + 12).lineTo(550, y + 12).strokeColor('#cccccc').stroke();
    y += 25;

    doc.fontSize(10).font('Helvetica').fillColor('#1a1a2e');
    for (const item of items) {
      const itemTotal = item.quantity * item.price;
      doc.text(item.description, 50, y);
      doc.text(String(item.quantity), 300, y);
      doc.text(formatCurrency(item.price, default_currency), 400, y);
      doc.text(formatCurrency(itemTotal, default_currency), 500, y);
      y += 20;
    }

    // Total
    y += 10;
    doc.moveTo(300, y).lineTo(550, y).strokeColor('#cccccc').stroke();
    doc.fontSize(11).font('Helvetica-Bold').text('Total:', 400, y + 5, { align: 'right' });
    doc.fontSize(11).font('Helvetica-Bold').text(formatCurrency(total_amount, default_currency), 500, y + 5, { align: 'right' });

    // Terms
    y += 40;
    if (terms_and_notes) {
      doc.fontSize(9).font('Helvetica-Bold').text('Terms & Notes:', 50, y);
      doc.fontSize(9).font('Helvetica').text(terms_and_notes, 50, y + 12, { width: 500 });
      y += 40;
    }

    // Footer
    doc.fontSize(8).font('Helvetica').fillColor('#888888');
    doc.text('Generated by PataReceipt - Secured by PataReceipt', 50, 750, { align: 'center', width: 500 });
    doc.text('This receipt is tamper-proof and verifiable via PataReceipt', 50, 760, { align: 'center', width: 500 });

    doc.end();
  });
};

module.exports = { generateReceiptPdf, maskPhone, formatCurrency };